/** Colour is a class (`--c-maps` → `c-maps`) so the icon needs no inline style. */
export function ico(name: string, color: string | null, size?: number): string {
  const px = size || 18;
  const tone = color ? color.replace(/^--/, "") : "";
  const cls = tone ? `ico ${tone}` : "ico";
  return `<svg class="${cls}" width="${px}" height="${px}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${SVG[name] ?? ""}</svg>`;
}

/** A wide wordmark (eBay) is drawn 12px tall by `.plogo.wm` instead of an inline width. */
export function brandIcon(platform: string): string {
  const icon = SI[platform];
  if (!icon) return "";
  const box = icon[1].split(" ").map(Number);
  const wide = (box[2] ?? 0) / (box[3] ?? 1) > 1.6;
  return `<svg class="plogo${wide ? " wm" : ""}" viewBox="${icon[1]}" aria-hidden="true" focusable="false"><path d="${icon[0]}"/></svg>`;
}
